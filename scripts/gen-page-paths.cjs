// Regenerates lib/pagePaths.js: pageKey -> public URL path, scanned from
// every app/(main)/**/page.js that calls buildPageMetadata("<key>", ...).
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..", "app", "(main)");
const out = {};
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name === "page.js") {
      const m = fs.readFileSync(p, "utf8").match(/buildPageMetadata\(\s*"([^"]+)"/);
      if (!m) continue;
      const rel = path.relative(root, dir).split(path.sep).join("/");
      out[m[1]] = rel ? "/" + rel : "/";
    }
  }
})(root);
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(
  path.join(__dirname, "..", "lib", "pagePaths.js"),
  "// GENERATED by scripts/gen-page-paths.cjs — pageKey -> public URL path.\n" +
    "export const PAGE_PATHS = " + JSON.stringify(sorted, null, 2) + ";\n\n" +
    "export const SITE_URL = \"https://bizzbuzzcreations.com\";\n\n" +
    "export const PATH_TO_PAGE_KEY = Object.fromEntries(\n  Object.entries(PAGE_PATHS).map(([k, v]) => [v, k]),\n);\n",
);
console.log(Object.keys(sorted).length, "pages");
